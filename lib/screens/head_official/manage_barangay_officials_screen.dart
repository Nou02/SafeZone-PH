import 'dart:math';
import 'package:flutter/material.dart';
import 'package:supabase_flutter/supabase_flutter.dart';
import '../../utils/app_colors.dart';
import '../../utils/role_helper.dart';
import 'set_barangay_hall_screen.dart';

class ManageBarangayOfficialsScreen extends StatefulWidget {
  const ManageBarangayOfficialsScreen({super.key});

  @override
  State<ManageBarangayOfficialsScreen> createState() => _ManageBarangayOfficialsScreenState();
}

class _ManageBarangayOfficialsScreenState extends State<ManageBarangayOfficialsScreen> with SingleTickerProviderStateMixin {
  final SupabaseClient _client = Supabase.instance.client;
  late TabController _tabController;
  
  // Passcode management
  List<Map<String, dynamic>> _generatedPasscodes = [];
  bool _loadingPasscodes = true;
  String? _barangayId;
  String? _barangayName;

  // Officials management
  List<Map<String, dynamic>> _officials = [];
  bool _loadingOfficials = true;

  @override
  void initState() {
    super.initState();
    _tabController = TabController(length: 2, vsync: this);
    _loadData();
  }

  @override
  void dispose() {
    _tabController.dispose();
    super.dispose();
  }

  Future<void> _loadData() async {
    await Future.wait([
      _loadPasscodes(),
      _loadOfficials(),
    ]);
  }

  Future<void> _loadPasscodes() async {
    setState(() => _loadingPasscodes = true);
    try {
      final barangayId = RoleHelper.getBarangayId();
      if (barangayId != null) {
        _barangayId = barangayId;
        // Get barangay name
        final barangayRes = await _client
            .from('barangays')
            .select('name')
            .eq('id', barangayId)
            .maybeSingle();
        if (barangayRes != null) {
          _barangayName = barangayRes['name'] as String?;
        }

        // Load generated passcodes
        final passcodesRes = await _client
            .from('barangay_official_passcodes')
            .select()
            .eq('barangay_id', barangayId)
            .order('created_at', ascending: false);
        setState(() {
          _generatedPasscodes = List<Map<String, dynamic>>.from(passcodesRes);
          _loadingPasscodes = false;
        });
      } else {
        setState(() => _loadingPasscodes = false);
      }
    } catch (e) {
      setState(() => _loadingPasscodes = false);
    }
  }

  Future<void> _loadOfficials() async {
    setState(() => _loadingOfficials = true);
    try {
      final userId = _client.auth.currentUser?.id;
      if (userId == null) {
        setState(() {
          _officials = [];
          _loadingOfficials = false;
        });
        return;
      }

      // Get all passcodes generated by this Head Official
      // We'll filter for used ones in the app since RLS might be blocking the filter
      final response = await _client
          .from('barangay_official_passcodes')
          .select('used_by_user_id, used_by_name, used_by_email, used_at, passcode, created_at')
          .eq('generated_by_user_id', userId)
          .order('created_at', ascending: false);

      // Filter for used passcodes and get unique user IDs
      final Map<String, Map<String, dynamic>> officialsMap = {};
      for (final row in response) {
        final usedByUserId = row['used_by_user_id'] as String?;
        if (usedByUserId != null && usedByUserId.isNotEmpty) {
          // Only add if not already in map (to get the most recent verification)
          if (!officialsMap.containsKey(usedByUserId)) {
            officialsMap[usedByUserId] = {
              'user_id': usedByUserId,
              'name': row['used_by_name'] ?? 'Unknown',
              'email': row['used_by_email'] ?? '',
              'verified_at': row['used_at'],
              'passcode_used': row['passcode'],
              'first_passcode_created': row['created_at'],
            };
          }
        }
      }

      // Try to get user metadata for each user
      final List<Map<String, dynamic>> officialsList = [];
      for (final official in officialsMap.values) {
        // We can't directly query auth.users, but we can try to get info from a user_profiles table
        // or just show what we have. For now, we'll show the user ID and verification date.
        // In a production app, you'd want to create a user_profiles table or use a database function.
        officialsList.add(official);
      }

      setState(() {
        _officials = officialsList;
        _loadingOfficials = false;
      });
    } catch (e) {
      if (!mounted) return;
      setState(() {
        _officials = [];
        _loadingOfficials = false;
      });
      // Log error for debugging
      debugPrint('Error loading officials: $e');
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Error loading officials: $e'),
          duration: const Duration(seconds: 5),
        ),
      );
    }
  }

  String _generatePasscode() {
    const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
    final random = Random();
    return List.generate(8, (_) => chars[random.nextInt(chars.length)]).join();
  }

  Future<void> _generateNewPasscode() async {
    if (_barangayId == null) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Barangay ID not found')),
      );
      return;
    }

    final userId = _client.auth.currentUser?.id;
    if (userId == null) return;

    try {
      final passcode = _generatePasscode();
      await _client.from('barangay_official_passcodes').insert({
        'barangay_id': _barangayId,
        'generated_by_user_id': userId,
        'passcode': passcode,
      });
      if (!mounted) return;
      _loadPasscodes();
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('Passcode generated: $passcode'),
          duration: const Duration(seconds: 5),
        ),
      );
    } catch (e) {
      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('Failed to generate: $e')),
      );
    }
  }


  String _formatDate(dynamic date) {
    if (date == null) return 'Unknown';
    try {
      final dt = DateTime.parse(date.toString());
      return '${dt.day}/${dt.month}/${dt.year}';
    } catch (e) {
      return date.toString();
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text('Manage Barangay Officials'),
        actions: [
          IconButton(
            icon: const Icon(Icons.location_on),
            onPressed: () {
              Navigator.of(context).push(
                MaterialPageRoute(
                  builder: (_) => const SetBarangayHallScreen(),
                ),
              );
            },
            tooltip: 'Set Barangay Hall Location',
          ),
        ],
        bottom: TabBar(
          controller: _tabController,
          tabs: const [
            Tab(icon: Icon(Icons.vpn_key), text: 'Passcodes'),
            Tab(icon: Icon(Icons.people), text: 'Officials'),
          ],
        ),
      ),
      body: TabBarView(
        controller: _tabController,
        children: [
          // Passcodes Tab
          _buildPasscodesTab(),
          // Officials Tab
          _buildOfficialsTab(),
        ],
      ),
    );
  }

  Widget _buildPasscodesTab() {
    return Column(
      children: [
        if (_barangayName != null)
          Container(
            width: double.infinity,
            padding: const EdgeInsets.all(16),
            color: Theme.of(context).colorScheme.primaryContainer,
            child: Text(
              'Barangay: $_barangayName',
              style: Theme.of(context).textTheme.titleMedium,
              textAlign: TextAlign.center,
            ),
          ),
        Padding(
          padding: const EdgeInsets.all(16),
          child: FilledButton.icon(
            onPressed: _generateNewPasscode,
            icon: const Icon(Icons.add),
            label: const Text('Generate New Passcode'),
            style: FilledButton.styleFrom(
              backgroundColor: AppColors.primary,
              minimumSize: const Size(double.infinity, 48),
            ),
          ),
        ),
        Expanded(
          child: _loadingPasscodes
              ? const Center(child: CircularProgressIndicator())
              : _generatedPasscodes.isEmpty
                  ? Center(
                      child: Column(
                        mainAxisAlignment: MainAxisAlignment.center,
                        children: [
                          const Icon(Icons.vpn_key_outlined, size: 64, color: Colors.grey),
                          const SizedBox(height: 16),
                          const Text(
                            'No passcodes generated yet',
                            style: TextStyle(color: Colors.grey),
                          ),
                        ],
                      ),
                    )
                  : ListView.builder(
                      padding: const EdgeInsets.all(16),
                      itemCount: _generatedPasscodes.length,
                      itemBuilder: (context, index) {
                        final passcode = _generatedPasscodes[index];
                        final isUsed = passcode['used_by_user_id'] != null;
                        return Card(
                          margin: const EdgeInsets.only(bottom: 8),
                          color: isUsed ? Colors.grey.shade100 : null,
                          child: ListTile(
                            leading: Icon(
                              isUsed ? Icons.check_circle : Icons.vpn_key,
                              color: isUsed ? Colors.green : Colors.blue,
                            ),
                            title: Text(
                              passcode['passcode'] ?? 'N/A',
                              style: TextStyle(
                                fontFamily: 'monospace',
                                fontSize: 18,
                                fontWeight: FontWeight.bold,
                                color: isUsed ? Colors.grey : null,
                              ),
                            ),
                            subtitle: Column(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                                if (isUsed)
                                  const Text(
                                    'Used',
                                    style: TextStyle(color: Colors.green),
                                  )
                                else
                                  const Text(
                                    'Available',
                                    style: TextStyle(color: Colors.blue),
                                  ),
                                Text(
                                  'Created: ${_formatDate(passcode['created_at'])}',
                                  style: const TextStyle(fontSize: 12),
                                ),
                              ],
                            ),
                          ),
                        );
                      },
                    ),
        ),
      ],
    );
  }

  Widget _buildOfficialsTab() {
    return _loadingOfficials
        ? const Center(child: CircularProgressIndicator())
        : _officials.isEmpty
            ? Center(
                child: Column(
                  mainAxisAlignment: MainAxisAlignment.center,
                  children: [
                    const Icon(Icons.people_outline, size: 64, color: Colors.grey),
                    const SizedBox(height: 16),
                    const Text(
                      'No verified officials yet',
                      style: TextStyle(color: Colors.grey),
                    ),
                    const SizedBox(height: 8),
                    Text(
                      'Officials will appear here after they verify using a passcode you generated.',
                      style: TextStyle(color: Colors.grey.shade600, fontSize: 12),
                      textAlign: TextAlign.center,
                    ),
                  ],
                ),
              )
            : ListView.builder(
                padding: const EdgeInsets.all(16),
                itemCount: _officials.length,
                itemBuilder: (context, index) {
                  final official = _officials[index];
                  final userName = official['name'] as String? ?? 'Unknown';
                  final userEmail = official['email'] as String? ?? '';
                  final verifiedAt = official['verified_at'] as String?;
                  final passcodeUsed = official['passcode_used'] as String?;
                  
                  String verifiedDate = 'Unknown';
                  if (verifiedAt != null) {
                    try {
                      final dt = DateTime.parse(verifiedAt);
                      verifiedDate = '${dt.day}/${dt.month}/${dt.year}';
                    } catch (e) {
                      verifiedDate = verifiedAt;
                    }
                  }

                  return Card(
                    margin: const EdgeInsets.only(bottom: 8),
                    child: ListTile(
                      leading: const CircleAvatar(
                        child: Icon(Icons.verified_user, color: Colors.green),
                      ),
                      title: Text(
                        userName,
                        style: const TextStyle(fontWeight: FontWeight.w600),
                      ),
                      subtitle: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          if (userEmail.isNotEmpty)
                            Text(
                              userEmail,
                              style: TextStyle(color: Colors.grey.shade600, fontSize: 12),
                            ),
                          const SizedBox(height: 4),
                          const Text(
                            'Verified Barangay Official',
                            style: TextStyle(fontWeight: FontWeight.w500),
                          ),
                          Text('Verified: $verifiedDate'),
                          if (passcodeUsed != null)
                            Text(
                              'Passcode: $passcodeUsed',
                              style: const TextStyle(
                                fontFamily: 'monospace',
                                fontSize: 12,
                                color: Colors.grey,
                              ),
                            ),
                        ],
                      ),
                      trailing: const Icon(Icons.check_circle, color: Colors.green),
                    ),
                  );
                },
              );
  }
}

